#!/usr/bin/env node
// Renders cordis.patch.yml at the repository root (the bundle layer of the installable package, package.json's
// dsh.bundle.patch) from profiles/bundle/cordis.patch.yml.in and the 电脑操作 preset in profiles/presets/cu-desktop:
// its name, description and order from preset.yml, its plugin rows (the persona) from agent.cordis.yml. That preset
// directory is the bundle's only source of the mode's persona and name; nothing else renders it.
//
//   node scripts/gen-bundle-patch.mjs           write cordis.patch.yml
//   node scripts/gen-bundle-patch.mjs --check   exit 1 if it is not current (plugin/tests/bundle.test.mjs does this)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const OUTPUT = 'cordis.patch.yml'

const HEADER = [
  '# GENERATED by scripts/gen-bundle-patch.mjs from profiles/bundle/cordis.patch.yml.in and profiles/presets/cu-desktop.',
  '# Edit those, then run `node scripts/gen-bundle-patch.mjs`; plugin/tests/bundle.test.mjs checks this file is current.',
  '',
  '',
]

const quote = (v) => `'${v.replaceAll("'", "''")}'`

/**
 * @param {string} root - the repository root.
 * @returns {string} the bundle patch's text.
 */
export function renderBundlePatch(root = ROOT) {
  const presets = join(root, 'profiles/presets/cu-desktop')
  const meta = {}
  for (const line of readFileSync(join(presets, 'preset.yml'), 'utf8').split('\n')) {
    const m = /^(\w+):\s*(.*?)\s*$/.exec(line)
    if (m) meta[m[1]] = m[2]
  }
  for (const key of ['name', 'description', 'order']) {
    if (!meta[key]) throw new Error(`profiles/presets/cu-desktop/preset.yml has no ${key}`)
  }
  const rows = readFileSync(join(presets, 'agent.cordis.yml'), 'utf8').split('\n').filter((l) => !/^\s*#/.test(l))
  while (rows.length > 0 && rows.at(-1).trim() === '') rows.pop()
  const persona = rows.map((l) => (l.trim() === '' ? '' : `          ${l}`)).join('\n')
  const template = readFileSync(join(root, 'profiles/bundle/cordis.patch.yml.in'), 'utf8')
  const out = template
    .replace('@NAME@', quote(meta.name))
    .replace('@DESCRIPTION@', quote(meta.description))
    .replace('@ORDER@', String(Number(meta.order)))
    .replace('@PERSONA@', persona)
  if (/@[A-Z]+@/.test(out)) throw new Error(`a placeholder is left in ${OUTPUT}: ${/@[A-Z]+@/.exec(out)[0]}`)
  return HEADER.join('\n') + out
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const path = join(ROOT, OUTPUT)
  const text = renderBundlePatch()
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(path, 'utf8')
    } catch (e) {
      // No file yet counts as out of date.
      void e
    }
    if (current !== text) {
      console.error(`${OUTPUT} is not current: run node scripts/gen-bundle-patch.mjs`)
      process.exit(1)
    }
  } else {
    writeFileSync(path, text)
    console.log(`wrote ${OUTPUT}`)
  }
}
