#!/usr/bin/env python3
"""R5 latency from the one-VM serial runs (bench/r5/latency.json, run ids r5-latency-<arm>).

    python3 bench/r5/latency.py

Per arm: job wall time, the part spent inside the daemon (sum of the audit's dur_ms over the job: observe incl.
capture + OCR, zoom, actions), the rest (model turns, dsh, plugin, IPC), and per-call daemon times. Refuses runs that
were not alone on the host (vm.json parallel_vms != 1).
"""
from __future__ import annotations

import json
import statistics as st
from collections import defaultdict
from pathlib import Path

RUNS = Path(__file__).resolve().parent.parent / 'runs'


def pct(v: list[float], q: float) -> float:
    v = sorted(v)
    return v[min(len(v) - 1, int(q * len(v)))] if v else float('nan')


def main() -> None:
    rows, calls = [], defaultdict(lambda: defaultdict(list))
    for run in sorted(RUNS.glob('r5-latency-*')):
        vm = json.loads((run / 'vm.json').read_text())
        if vm.get('parallel_vms') != 1:
            raise SystemExit(f'{run.name}: parallel_vms={vm.get("parallel_vms")}, not latency data')
        score = json.loads((run / 'score.json').read_text())['jobs']
        for j in score:
            d = run / j['task'] / j['mode'] / f'k{j["k"]}'
            daemon = 0.0
            for line in (d / 'audit.jsonl').read_text().splitlines():
                e = json.loads(line)
                if 'dur_ms' in e:
                    daemon += e['dur_ms'] / 1000
                    calls[j['arm']][e['method']].append(e['dur_ms'])
            rows.append({'arm': j['arm'], 'cell': f'{j["task"]}/{j["mode"]}', 'wall': j['wall_s'], 'daemon': daemon,
                         'steps': (j.get('transcript') or {}).get('steps', 0), 'pass': j['pass']})
    arms = sorted({r['arm'] for r in rows})
    out = ['# R5 latency (one VM, serial; generated by bench/r5/latency.py)', '',
           '| arm | jobs | pass | wall p50 s | wall mean s | in daemon, mean s | rest (model, dsh, plugin), mean s | steps p50 |',
           '|---|---|---|---|---|---|---|---|']
    for a in arms:
        rs = [r for r in rows if r['arm'] == a]
        out.append(f'| {a} | {len(rs)} | {sum(r["pass"] for r in rs)}/{len(rs)} | {pct([r["wall"] for r in rs], .5):.1f} | '
                   f'{st.mean(r["wall"] for r in rs):.1f} | {st.mean(r["daemon"] for r in rs):.1f} | '
                   f'{st.mean(r["wall"] - r["daemon"] for r in rs):.1f} | {pct([r["steps"] for r in rs], .5)} |')
    out += ['', '## Per cell: wall s (mean of k)', '', '| cell | ' + ' | '.join(arms) + ' |', '|---|' + '---|' * len(arms)]
    for c in sorted({r['cell'] for r in rows}):
        out.append(f'| {c} | ' + ' | '.join(
            f'{st.mean(r["wall"] for r in rows if r["arm"] == a and r["cell"] == c):.1f}'
            if any(r['arm'] == a and r['cell'] == c for r in rows) else '' for a in arms) + ' |')
    out += ['', '## Daemon calls (ms)', '', '| arm | method | n | p50 | p90 | max |', '|---|---|---|---|---|---|']
    for a in arms:
        for m in ('observe', 'zoom', 'act.click', 'act.type', 'act.key', 'act.scroll'):
            v = calls[a].get(m)
            if v:
                out.append(f'| {a} | {m} | {len(v)} | {pct(v, .5):.0f} | {pct(v, .9):.0f} | {max(v):.0f} |')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
