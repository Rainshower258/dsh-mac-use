#!/usr/bin/env python3
"""Collect bench/results/offline/*.json into bench/results/offline/summary.md."""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'results/offline'
BUCKETS = ['msg-body', 'msg-meta', 'msg-small', 'msg-faint', 'msg-code', 'msg-image', 'sidebar', 'ui']
SLICES = ['mode:dom', 'mode:canvas', 'mode:image', 'theme:light', 'theme:dark']


def pct(v) -> str:
    return '—' if v is None else f'{v:.1%}'


def num(v, fmt='{:.0f}') -> str:
    return '—' if v is None else fmt.format(v)


def main() -> None:
    results = [json.loads(p.read_text()) for p in sorted(OUT.glob('*.json'))]
    results.sort(key=lambda r: (r['cer']['all']['strict'] if r['cer'].get('all') else 9))
    md = ['# Offline read-screen bench — summary', '',
          f'Corpus: `{results[0]["corpus"]}` ({results[0]["images"]} images). Generated by `bench/offline/summarize.py`; '
          'regenerate after `bench/offline/run.py --backend <name>`.', '',
          'CER is computed per ground-truth line against the best-matching substring of the backend output '
          '(whitespace removed; *loose* also NFKC-folds width variants such as `，`/`,`, `℃`/`°C`). '
          'Key strings must appear character-for-character (whitespace-insensitive; *loose* allows width folding only — '
          '`l`/`1`/`I` and `O`/`0` confusions still fail). bbox hit = a box reading a button/conversation label has its centre inside that element.', '',
          '## Overview', '',
          '| backend | CER strict | CER loose | key strict | key loose | bbox hit | p50 ms | p95 ms | cold start ms | peak RSS MB |',
          '|---|---|---|---|---|---|---|---|---|---|']
    for r in results:
        a, k, kl, b, lat, meta = r['cer']['all'], r['keystring_recall']['all'], r.get('keystring_recall_loose', {}).get('all', {}), r['bbox_hit_rate']['all'], r['latency_ms'], r['meta']
        bbox = f"{pct(b['rate'])} ({b['hit']}/{b['total']})" if meta.get('has_bbox') else 'n/a'
        md.append(f"| `{r['backend']}` | {pct(a['strict'])} | {pct(a['loose'])} | {pct(k['recall'])} ({k['hit']}/{k['total']}) | "
                  f"{pct(kl.get('recall'))} | {bbox} | {num(lat['p50'])} | {num(lat['p95'])} | "
                  f"{num(meta.get('cold_start_ms') or meta.get('first_request_ms'))} | {num(meta.get('peak_rss_mb'))} |")

    md += ['', '## CER (strict) by line type', '', '| backend | ' + ' | '.join(BUCKETS) + ' |', '|---' * (len(BUCKETS) + 1) + '|']
    for r in results:
        md.append(f"| `{r['backend']}` | " + ' | '.join(pct(r['cer'].get(b, {}).get('strict')) for b in BUCKETS) + ' |')

    md += ['', '## By render mode / theme', '', '| backend | ' + ' | '.join(f'CER {s}' for s in SLICES) + ' | ' + ' | '.join(f'key {s}' for s in SLICES[:3]) + ' |',
           '|---' * (len(SLICES) + 4) + '|']
    for r in results:
        md.append(f"| `{r['backend']}` | " + ' | '.join(pct(r['cer'].get(s, {}).get('strict')) for s in SLICES) + ' | '
                  + ' | '.join(pct(r['keystring_recall'].get(s, {}).get('recall')) for s in SLICES[:3]) + ' |')

    md += ['', '## Key strings missed (strict), with a typical misreading', '']
    for r in results:
        miss, total, example = Counter(), Counter(), {}
        for p in r['per_image']:
            for key, ok in p['keystrings'].items():
                total[key] += 1
                if not ok:
                    miss[key] += 1
                    for line in p['lines']:
                        # Only show a misreading that actually overlaps the line.
                        if key.replace(' ', '') in line['gt'].replace(' ', '') and line['pred'] and line['dist'] < 0.5 * line['len']:
                            example.setdefault(key, line['pred'])
        if not miss:
            md.append(f"- `{r['backend']}`: none missed")
            continue
        md.append(f"- `{r['backend']}`: " + '; '.join(
            f"`{key}` {miss[key]}/{total[key]}" + (f" → “{example[key][:60]}”" if key in example else '') for key in sorted(miss, key=lambda x: -miss[x])))
    md += ['', '## Backend notes', '']
    for r in results:
        note = r['meta'].get('note')
        flags = r['meta'].get('flags')
        md.append(f"- `{r['backend']}`: generated {r['generated']}" + (f"; flags {flags}" if flags else '') + (f"; {note}" if note else ''))
    (OUT / 'summary.md').write_text('\n'.join(md) + '\n')
    print(OUT / 'summary.md')


if __name__ == '__main__':
    main()
